export type SyllabusModule = {
  title: string;
  learn: string; // מה לומדים
  practice: string; // מה מתרגלים
  build: string; // מה בונים
  takeaway: string; // עם מה יוצאים בסוף החלק
};

export type CourseFaq = { q: string; a: string };

export type CourseCardPill = {
  icon: "bolt" | "users" | "target" | "spark";
  label: string;
};

